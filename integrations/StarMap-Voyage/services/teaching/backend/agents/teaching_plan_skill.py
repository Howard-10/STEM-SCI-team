def build_system_prompt(grade_level: str, difficulty, include_3d_print: bool) -> str:
    """构造 system prompt：角色 + SOP + 输出模板 + 关键原则。"""

    try:
        difficulty = int(difficulty) if difficulty not in (None, "") else 0
    except (TypeError, ValueError):
        difficulty = 0
    diff_hint = ""
    if difficulty:
        diff_hint = f"难度要求：{'⭐' * difficulty}（{difficulty}/4 级）"

    prompt = f"""你是一位经验丰富的 K-12 STEM 教育专家，长期为中小学设计项目式学习（PBL）教案。

## 你的任务
根据学生提出的主题，生成一份【完整、贴合主题、可直接使用】的 STEM 项目式学习教学设计。

## 学生信息
- 目标学段：{grade_level}
- {diff_hint}

## 生成步骤（SOP）
1. 深度拆解主题：先明确该主题的核心科学概念、关键技术、真实应用场景，围绕它们组织内容；
2. 分析学情：结合学段，写出认知特点、已有基础、可能困难；
3. 设定素养目标：按 S/T/E/A/M 与 AI 素养分维度，每条以「学生能够……」开头；
4. 规划资源：材料清单要具体真实（型号、数量、规格），软件环境要可落地；
5. 设计分课时教学过程：每个课时安排 2~4 个环节，写出分钟数、组织方式、教师操作、学生操作步骤、过程记录、学生产出、教师追问与可能回答；“设计意图”必须放在该环节所有活动描述的最后，不能夹在步骤中间；课时内只记录观察点和即时反馈，不放正式评价表或总评等级；
6. 在所有课时之后单独设计“教学评价”或“评价与总结”章节，集中呈现教师评价表、学生自评、组内互评、展示互评、评分维度与总结拓展。

## 教案输出格式（必须严格遵守，用 # 一级标题，## 二级标题，### 三级标题）

{OUTPUT_STRUCTURE}

## 关键原则
- 高度贴合主题：所有材料、步骤、提问、评价都必须针对该主题的具体内容，禁止套用泛化模板话术；
- 语言亲切，用「你」直接与学生对话；
- 不要直接复制参考示例的内容，只学习其结构、颗粒度与风格，内容必须全新创作；
- 必须选择一个明确的具体年级，不得只写“小学生”“初中生”“高中生”；如果主题涉及三角函数、正弦定律、成像公式等内容，应明确定位为初中三年级或高中相应年级，并列出前置知识与降阶处理；
- 每个课时、每个环节都要有明确的学生产出；每个活动至少给出 3 个连续可执行步骤，不能只写“讨论、完成、展示”等结果性描述；课时环节不展开正式评价量表，统一评价放在文末“教学评价”章节；
- 每一个教学活动都必须回答“怎么做”：每个活动包含教师组织、学生至少 3 步操作、记录/产出；写清材料如何摆放、教师说什么或演示什么、学生按什么顺序操作、记录哪些数据；设计意图必须放在该环节最后；
- 每个课时的活动总时长必须与课时长度一致（默认 45 分钟），并写出课时小结和课后任务；
- 不得使用“略”“同上”“后续展开”“视情况而定”等省略表达；
- 安全提示必须具体（激光 / 电路 / 高温 / 化学 / 工具等），不能泛泛而谈。
"""

    if include_3d_print:
        prompt += "\n\n- 如项目涉及传感器、机械结构或实验装置，请在「教学资源」中标注可 3D 打印的部件，并给出简要设计思路。"

    return prompt


def build_user_message(
    user_query: str,
    grade_desc: str,
    examples,
    knowledge_context: str,
    include_3d_print: bool,
) -> str:
    """构造 user message：学生需求 + 参考知识 + 参考教案示例 + 生成要求。"""

    parts = [
        f"请为一位{grade_desc}的学生设计一份 STEM 项目式学习教学设计。",
        "",
        f"学生说：\"{user_query}\"",
        "",
    ]

    if knowledge_context:
        parts.append("## 参考知识片段（与主题直接相关，请据此保证内容准确、贴合）")
        parts.append(knowledge_context)
        parts.append("")

    if examples:
        parts.append("## 参考教案示例（请学习其结构、颗粒度与风格，内容必须全新创作）")
        for i, example in enumerate(examples[:2], 1):
            truncated = example[:3000] if len(example) > 3000 else example
            parts.append(f"### 示例{i}")
            parts.append(truncated)
            parts.append("")

    parts.append("## 生成要求")
    parts.append("请严格按 system prompt 中给出的输出格式，生成一份完整、贴合主题的 STEM 教学设计：")
    parts.append("- 用 # 一级标题写项目标题，## 二级标题写各章节，### 三级标题写分课时；")
    parts.append("- 教学目标分 S/T/E/A/M 与 AI 素养维度；")
    parts.append("- 教学过程分 3~6 个课时，每课时默认 45 分钟，含课时目标、STEAM 维度、2~4 个分环节活动、课时小结与课后任务；")
    parts.append("- 每个环节都要按‘教师如何组织 → 学生如何操作（至少3步）→ 过程记录/学生产出 → 教师提问与可能回答 → 设计意图’顺序书写；每个活动包含教师组织、学生至少 3 步操作、记录/产出；设计意图必须是该环节最后一项；课时内不放正式评价表或总评等级；")
    parts.append("- 必须在‘适用学段与年级’中写出具体年级，并检查所有数学和科学概念不超出该年级的前置知识；")
    parts.append("- 六个课时（如采用六课时）都要写完整过程，不能用一句话概括第2课时及以后内容；")
    parts.append("- 材料清单具体到型号与数量；")
    parts.append("- 所有分课时完成后，最后单独包含「教学评价」或「评价与总结」与「安全提示」（如适用）。")
    if include_3d_print:
        parts.append("- 如涉及传感器、机械结构或实验装置，在「教学资源」中标注可 3D 打印的部件。")

    return "\n".join(parts)
